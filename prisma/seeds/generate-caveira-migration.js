/**
 * One-off generator: builds a STATIC Prisma data-migration from a YouTube playlist.
 *
 * A Prisma migration runs offline SQL (no network at deploy time), so the playlist
 * must be fetched HERE, at authoring time, and baked into the migration.sql.
 *
 * Requires `yt-dlp` on PATH (e.g. `brew install yt-dlp`). NOT run in production.
 *
 * Usage:
 *   node prisma/seeds/generate-caveira-migration.js <migration-sql-path> [playlistUrl]
 *
 * Where <migration-sql-path> is the migration.sql created by:
 *   npx prisma migrate dev --create-only --name add_caveira_exercise_templates
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { inferExerciseType } from '../../src/helpers/exercise-type-infer.js';
import {
  normalizeExerciseName,
  exerciseDedupKey,
} from '../../src/helpers/exercise-name-normalize.js';

const DEFAULT_PLAYLIST =
  'https://www.youtube.com/playlist?list=PLTEMMx_kdcbU-5LocYvP_KpDYQ8KjZiWz';

// Owning trainer (trainers.id) of the seeded templates. Templates are PRIVATE
// (is_public=false). A bad id fails loudly via the FK constraint.
const TRAINER_ID = 'e150a1c0-8b72-4e09-b788-833019927b66';

/** SQL-escape a string literal (double single quotes). */
function sql(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** Deterministic UUID (v5-style, namespace-free) derived from the video id. */
function deterministicUuid(seed) {
  const h = createHash('sha1').update(`caveira:${seed}`).digest('hex');
  // Format 16 bytes as UUID, force version 5 + RFC-4122 variant.
  const b = h.slice(0, 32).split('');
  b[12] = '5';
  b[16] = ((parseInt(b[16], 16) & 0x3) | 0x8).toString(16);
  const s = b.join('');
  return `${s.slice(0, 8)}-${s.slice(8, 12)}-${s.slice(12, 16)}-${s.slice(16, 20)}-${s.slice(20, 32)}`;
}

function fetchPlaylist(url) {
  const raw = execFileSync(
    'yt-dlp',
    ['--flat-playlist', '--print', '%(id)s\t%(title)s', url],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  return raw
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const tab = line.indexOf('\t');
      return { id: line.slice(0, tab), title: line.slice(tab + 1).trim() };
    })
    .filter((v) => v.id && v.title);
}

function buildSql(videos) {
  const seen = new Set();
  const rows = [];
  let dropped = 0;

  for (const v of videos) {
    const type = inferExerciseType(v.title);
    const name = normalizeExerciseName(v.title);
    // Collapse near-duplicates (same exercise, different wording/casing/º).
    const dedupKey = `${type}::${exerciseDedupKey(name)}`;
    if (seen.has(dedupKey)) {
      dropped += 1;
      continue;
    }
    seen.add(dedupKey);
    rows.push({
      id: deterministicUuid(v.id),
      name,
      type,
      videoUrl: `https://www.youtube.com/watch?v=${v.id}`,
    });
  }

  const header = `-- Auto-generated by prisma/seeds/generate-caveira-migration.js
-- PRIVATE exercise-template catalog seeded from the "Caveira Team" YouTube playlist.
-- Owner: trainer ${TRAINER_ID} (is_public=false). Seeding is gated on this trainer
-- existing, so the migration is a safe no-op on fresh/CI databases.
-- Idempotent: inserts use ON CONFLICT (id) DO NOTHING.

-- 1. Soft-delete this trainer's CURRENT templates (reversible; no FK cascade).
--    Runs BEFORE the inserts below, so the freshly seeded rows are NOT affected.
UPDATE "exercise_templates"
SET "deleted_at" = NOW()
WHERE "trainer_id" = ${sql(TRAINER_ID)} AND "deleted_at" IS NULL;

-- 2. Insert ${rows.length} private exercise templates.
--    Gated on the owning trainer existing: on a fresh/CI database (where this
--    staging-specific trainer is absent) the SELECT yields 0 rows and nothing is
--    inserted, so the migration stays portable and never hits an FK error.
INSERT INTO "exercise_templates" ("id", "trainer_id", "name", "type", "video_url", "is_public", "created_at")
SELECT v."id"::uuid, ${sql(TRAINER_ID)}::uuid, v."name", v."type", v."video_url", false, NOW()
FROM (
  VALUES`;

  const values = rows
    .map(
      (r) =>
        `    (${sql(r.id)}, ${sql(r.name)}, ${sql(r.type)}, ${sql(r.videoUrl)})`,
    )
    .join(',\n');

  const footer = `
) AS v("id", "name", "type", "video_url")
WHERE EXISTS (
  SELECT 1 FROM "trainers"
  WHERE "id" = ${sql(TRAINER_ID)} AND "deleted_at" IS NULL
)
ON CONFLICT ("id") DO NOTHING;
`;

  return { sqlText: `${header}\n${values}${footer}`, count: rows.length, dropped };
}

function main() {
  const outPath = process.argv[2];
  const playlistUrl = process.argv[3] || DEFAULT_PLAYLIST;
  if (!outPath) {
    console.error('Usage: node generate-caveira-migration.js <migration-sql-path> [playlistUrl]');
    process.exit(1);
  }

  console.log(`Fetching playlist: ${playlistUrl}`);
  const videos = fetchPlaylist(playlistUrl);
  console.log(`Fetched ${videos.length} videos.`);

  const { sqlText, count, dropped } = buildSql(videos);
  writeFileSync(outPath, sqlText, 'utf8');

  const byType = {};
  // quick type breakdown for sanity
  for (const v of videos) {
    const t = inferExerciseType(v.title);
    byType[t] = (byType[t] || 0) + 1;
  }
  console.log(`Wrote ${count} exercise templates to ${outPath}`);
  console.log(`Deduplicated (same type+title): ${dropped}`);
  console.log(`Type breakdown (pre-dedup):`, byType);
}

main();
